"""Negative control for a boundary-free rectangle conductivity decoder.

The conductivity reduction is well behaved once compatible Dirichlet data are
supplied.  This audit deliberately supplies the canonical identity boundary
to a coefficient generated by a nontrivial manufactured QC map.  It measures
whether a boundary choice can be treated as an innocuous implementation detail
for arbitrary ``mu``; a resolution-independent residual disproves that shortcut.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

from qcopt.forward.rectangle_conductivity import rectangle_beltrami_conductivity


def _manufactured(n: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    x = np.linspace(0.0, 1.0, n)
    xx, yy = np.meshgrid(x, x, indexing="xy")
    truth = xx + 0.08 * np.sin(2.0 * np.pi * yy) + 1j * yy
    beta = 0.08 * np.pi * np.cos(2.0 * np.pi * yy)
    mu = 1j * beta / (1.0 - 1j * beta)
    identity_boundary = xx + 1j * yy
    return mu.astype(np.complex128), truth.astype(np.complex128), identity_boundary.astype(np.complex128)


def run(output_dir: Path, sizes: tuple[int, ...] = (129, 257)) -> dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    records: list[dict] = []
    for n in sizes:
        mu, truth, identity_boundary = _manufactured(n)
        started = time.perf_counter()
        result = rectangle_beltrami_conductivity(mu, identity_boundary)
        elapsed = time.perf_counter() - started
        records.append(
            {
                "n_nodes_per_axis": int(n),
                "cells": int((n - 1) ** 2),
                "elapsed_seconds": float(elapsed),
                "equation_residual": float(result.equation_residual),
                "boundary_tangential_mismatch": float(result.boundary_imag_mismatch),
                "min_triangle_determinant": float(result.min_triangle_determinant),
                "map_rms_error_to_manufactured": float(np.sqrt(np.mean(np.abs(result.map - truth) ** 2))),
                "map_rms_error_to_identity": float(np.sqrt(np.mean(np.abs(result.map - identity_boundary) ** 2))),
                "finite": bool(np.all(np.isfinite(result.map))),
                "flipped": bool(result.min_triangle_determinant <= 0.0),
            }
        )
    residuals = [record["equation_residual"] for record in records]
    result = {
        "records": records,
        "scope": "boundary-free negative control: identity Dirichlet boundary imposed on a nontrivial manufactured Beltrami coefficient",
        "interpretation": "positive local Jacobian does not imply that a canonical rectangle boundary is compatible with arbitrary mu",
        "limitation": "this is a compatibility counterexample, not a search over optimal boundary normalization or a proof that no boundary solver exists",
        "residual_ratio_last_first": float(residuals[-1] / residuals[0]) if residuals else None,
    }
    (output_dir / "rectangle_boundary_free_control.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--sizes", type=int, nargs="+", default=[129, 257])
    args = parser.parse_args()
    print(json.dumps(run(args.output_dir, tuple(args.sizes)), indent=2))


if __name__ == "__main__":
    main()
