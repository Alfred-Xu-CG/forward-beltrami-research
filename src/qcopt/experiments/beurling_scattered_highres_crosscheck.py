"""High-resolution scattered Beurling treecode versus an external reference.

The reference is intentionally supplied as an array rather than generated by
this module, so the comparison can use a device-native direct evaluator on a
separate GPU host.  This keeps the treecode audit independent of its own
approximation and avoids any periodic-grid assumption.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

from qcopt.forward.beurling_treecode import treecode_beurling_apply


def generate_cloud(
    n: int,
    *,
    near: bool,
    near_offset: float | None = None,
    seed: int = 20260919,
) -> dict[str, np.ndarray]:
    rng = np.random.default_rng(seed + int(near))
    source = rng.random((n, 2))
    source[:, 0] *= 0.44
    source[:, 0] += 0.02
    source[:, 1] = 0.02 + 0.96 * source[:, 1]
    points = source[:, 0] + 1j * source[:, 1]
    if near and near_offset is not None:
        if near_offset <= 0.0 or not np.isfinite(near_offset):
            raise ValueError("near_offset must be positive and finite")
        angles = 2.0 * np.pi * rng.random(n)
        targets = points + near_offset * np.exp(1j * angles)
    else:
        target = rng.random((n, 2))
        target[:, 0] *= 0.44
        target[:, 0] += 0.54 if near else 0.74
        target[:, 1] = 0.02 + 0.96 * target[:, 1]
        targets = target[:, 0] + 1j * target[:, 1]
    values = rng.normal(size=n) + 1j * rng.normal(size=n)
    weights = (0.5 + rng.random(n)) / n
    return {
        "points": points.astype(np.complex128),
        "targets": targets.astype(np.complex128),
        "values": values.astype(np.complex128),
        "weights": weights.astype(np.float64),
    }


def run(
    output_dir: Path,
    n: int = 16384,
    theta: float = 0.22,
    order: int = 12,
    near: bool = False,
    near_offset: float | None = None,
    reference_path: Path | None = None,
) -> dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    cloud_path = output_dir / "scattered_cloud.npz"
    cloud = generate_cloud(n, near=near, near_offset=near_offset)
    np.savez(cloud_path, **cloud)
    started = time.perf_counter()
    tree = treecode_beurling_apply(
        cloud["points"],
        cloud["values"],
        cloud["weights"],
        target_points=cloud["targets"],
        theta=theta,
        order=order,
    )
    elapsed = time.perf_counter() - started
    record: dict[str, object] = {
        "points": n,
        "near_case": near,
        "theta": theta,
        "order": order,
        "near_offset": near_offset,
        "treecode_seconds": elapsed,
        "treecode_output_l2": float(np.linalg.norm(tree)),
        "treecode_finite": bool(np.all(np.isfinite(tree))),
    }
    np.save(output_dir / "treecode_output.npy", tree)
    if reference_path is not None:
        reference = np.load(reference_path)
        error = tree - reference
        record.update(
            {
                "reference_path": str(reference_path),
                "reference_output_l2": float(np.linalg.norm(reference)),
                "relative_l2_error": float(np.linalg.norm(error) / max(np.linalg.norm(reference), 1e-30)),
                "max_abs_error": float(np.max(np.abs(error))),
            }
        )
        metadata_path = reference_path.with_suffix(".json")
        if metadata_path.exists():
            metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
            for key in ("seconds", "interactions", "backend", "block_size"):
                if key in metadata:
                    record[f"reference_{key}"] = metadata[key]
    result = {
        "record": record,
        "cloud_path": str(cloud_path),
        "scope": f"nonperiodic scattered whole-plane Beurling treecode at {n:,} points",
        "limitation": "Barnes-Hut/Taylor control; production FMM and singular self-interaction treatment remain separate gates",
    }
    (output_dir / "beurling_scattered_highres_crosscheck.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8"
    )
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--n", type=int, default=16384)
    parser.add_argument("--theta", type=float, default=0.22)
    parser.add_argument("--order", type=int, default=12)
    parser.add_argument("--near", action="store_true")
    parser.add_argument("--near-offset", type=float, default=None)
    parser.add_argument("--reference", type=Path, default=None)
    args = parser.parse_args()
    print(json.dumps(run(args.output_dir, args.n, args.theta, args.order, args.near, args.near_offset, args.reference), indent=2))


if __name__ == "__main__":
    main()
